namespace CordMic.Core.Dsp;

/// <summary>
/// Render-side concealment of short output gaps (0.6.2), used when the Studio worker's ring runs short. Instead of
/// fading to silence (0.6.1: a 2 ms fade, an audible hole) it repeats the last pitch period of the output, phase
/// continuous, at full level for 10 ms, then fades over 20 ms; when real audio resumes it crossfades over 2 ms.
/// Original implementation (normalised autocorrelation over the last 5 ms, lags 2.5–20 ms). 48 kHz mono s16,
/// allocation-free, not thread-safe (the render thread owns it).
/// </summary>
public sealed class GapConcealer
{
    public const int History = 1440, Seg = 240, LagMin = 120, LagMax = 960, FullLen = 480, FadeLen = 960, Xfade = 96;
    private readonly float[] _h = new float[History];
    private int _hp, _hn;
    private int _gapPos = -1, _lag, _xf, _base;

    /// <summary>Samples generated by concealment so far.</summary>
    public long ConcealedSamples { get; private set; }
    /// <summary>Gaps started so far.</summary>
    public long Gaps { get; private set; }
    public bool InGap => _gapPos >= 0;

    public void Reset() { Array.Clear(_h); _hp = _hn = 0; _gapPos = -1; _lag = 0; _xf = 0; }

    /// <summary>Real audio: crossfades from the concealment if a gap just ended, then records it as history.</summary>
    public void Real(Span<short> s)
    {
        if (s.Length == 0) return;
        if (_gapPos >= 0 && _xf == 0) _xf = Xfade;
        for (int i = 0; i < s.Length; i++)
        {
            float v = s[i];
            if (_xf > 0)
            {
                double w = 0.5 - 0.5 * Math.Cos(Math.PI * (Xfade - _xf + 1) / (Xfade + 1));
                v = (float)(w * v + (1 - w) * Next());
                s[i] = (short)Math.Clamp((int)Math.Round(v), short.MinValue, short.MaxValue);
                if (--_xf == 0) _gapPos = -1;
            }
            _h[_hp] = v; if (++_hp == History) _hp = 0; if (_hn < History) _hn++;
        }
        if (_xf == 0) _gapPos = -1;
    }

    /// <summary>Fills a gap with concealment.</summary>
    public void Conceal(Span<short> s)
    {
        if (s.Length == 0) return;
        if (_gapPos < 0 || _xf > 0) { _xf = 0; if (_gapPos < 0) Start(); }
        for (int i = 0; i < s.Length; i++)
            s[i] = (short)Math.Clamp((int)Math.Round(Next()), short.MinValue, short.MaxValue);
        ConcealedSamples += s.Length;
    }

    private void Start()
    {
        Gaps++;
        _gapPos = 0;
        _base = _hp;
        _lag = _hn >= LagMax + Seg ? FindLag() : 0;
    }

    private float At(int back) => _h[((_hp - back) % History + History) % History]; // back = 1 is the newest sample
    private float AtBase(int back) => _h[((_base - back) % History + History) % History]; // relative to the gap start

    private readonly float[] _lin = new float[LagMax + Seg];

    private double Corr(int seg0, int lag, double e0)
    {
        double c = 0, e1 = 0;
        int b0 = seg0 - lag;
        for (int j = 0; j < Seg; j++) { double b = _lin[b0 + j]; c += _lin[seg0 + j] * b; e1 += b * b; }
        return c / Math.Sqrt(e0 * e1 + 1e-9);
    }

    private int FindLag()
    {
        // Linear copy of the newest LagMax + Seg samples (oldest first), then a plain normalised cross-correlation.
        int L = _lin.Length;
        for (int j = 0; j < L; j++) _lin[j] = At(L - j);
        int seg0 = L - Seg;
        double e0 = 0;
        for (int j = seg0; j < L; j++) e0 += _lin[j] * (double)_lin[j];
        // Coarse search on even lags, then refine around the best one (half the work of a full search).
        double best = double.NegativeInfinity; int bestLag = LagMin;
        for (int lag = LagMin; lag <= LagMax; lag += 2)
        {
            double r = Corr(seg0, lag, e0);
            if (r > best) { best = r; bestLag = lag; }
        }
        int c0 = bestLag;
        for (int lag = Math.Max(LagMin, c0 - 1); lag <= Math.Min(LagMax, c0 + 1); lag += 2)
        {
            double r = Corr(seg0, lag, e0);
            if (r > best) { best = r; bestLag = lag; }
        }
        return bestLag;
    }

    /// <summary>Next concealment sample: the last period repeated, full level for 10 ms, then a 20 ms raised-cosine fade.</summary>
    private float Next()
    {
        int p = _gapPos < 0 ? 0 : _gapPos;
        double g = p < FullLen ? 1 : p < FullLen + FadeLen ? 0.5 + 0.5 * Math.Cos(Math.PI * (p - FullLen + 1) / FadeLen) : 0;
        float v = 0;
        if (_lag > 0 && g > 0) v = (float)(g * AtBase(_lag - p % _lag));
        else if (_lag == 0 && _hn > 0 && p < Xfade) v = (float)(AtBase(1) * (0.5 + 0.5 * Math.Cos(Math.PI * (p + 1) / Xfade)));
        if (_gapPos >= 0) _gapPos++;
        return v;
    }
}
