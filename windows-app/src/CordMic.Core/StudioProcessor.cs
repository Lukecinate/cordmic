using System.Diagnostics;
using CordMic.Core.Dsp;

namespace CordMic.Core;

/// <summary>
/// Runs <see cref="StudioChain"/> on its own worker thread, off the audio callback (0.6.0 spec §8, CPU-2).
/// The render thread pulls finished s16 audio from a ring; each pull wakes the worker, which pulls 10 ms frames from
/// the jitter buffer, processes them and keeps the ring two frames plus one render period ahead (0.6.2: two frames
/// of added latency, one in 0.6.1). A deadline miss is a render pull that finds the ring short (an underflow; since
/// 0.6.2 the gap is concealed by <see cref="GapConcealer"/> instead of faded to silence) or a frame that took longer
/// than 10 ms to process. A preset change swaps the chain on the worker with a short crossfade
/// (<see cref="ReplaceChain"/>) instead of tearing the processor down. Three misses within one second raise <see cref="FellBack"/> once;
/// the receiver then switches Studio off for the session (CPU-4). No allocation after construction.
/// </summary>
public sealed class StudioProcessor : IDisposable
{
    public const int Frame = StudioChain.Frame;
    private const int RingCap = 48000 / 5; // 200 ms
    private const int WarmupFrames = 50;  // misses during the first 0.5 s (start-up, JIT) do not count

    /// <summary>Frames of worker buffering (0.6.2: 2).</summary>
    public const int BufferFrames = 2;
    /// <summary>Frames a replacement chain runs in parallel before the switch; the last one is crossfaded.</summary>
    public const int SwapWarmFrames = 3;

    private volatile StudioChain _chain;
    private StudioChain? _pending;
    private readonly float[] _f2 = new float[Frame];
    private readonly GapConcealer _gc = new();
    private readonly short[] _scratch = new short[RingCap];
    private long _underflows;
    private int _swapFrames;
    private readonly PullDelegate _pull;
    private readonly short[] _ring = new short[RingCap];
    private int _rRead, _rCount;
    private readonly object _ringLock = new();
    private readonly byte[] _pcm = new byte[Frame * 2];
    private readonly float[] _f = new float[Frame];
    private readonly short[] _s = new short[Frame];
    private readonly AutoResetEvent _wake = new(false);
    private readonly Thread _thread;
    private volatile bool _stop;
    private volatile bool _disposed;
    private volatile int _targetFill;
    private long _framesDone;
    private readonly long[] _missAt = new long[3];
    private int _missIdx;
    private int _fellBack;
    private double _procSum, _procMax;
    private long _procN;
    private readonly object _statLock = new();

    public delegate void PullDelegate(Span<byte> dst);

    /// <summary>Raised once (from the worker or render thread) after three missed deadlines within one second.</summary>
    public event Action<string>? FellBack;
    public StudioPreset Preset { get { var p = Volatile.Read(ref _pending); return (p ?? _chain).Preset; } }
    public long Misses { get; private set; }
    /// <summary>Render pulls that found the ring short after warm-up (each one concealed).</summary>
    public long Underflows => Interlocked.Read(ref _underflows);
    /// <summary>Samples generated by gap concealment so far.</summary>
    public long ConcealedSamples { get { lock (_ringLock) return _gc.ConcealedSamples; } }
    /// <summary>Completed chain swaps (diagnostics and tests).</summary>
    public int Swaps { get; private set; }
    public double AgcGainDb => _chain.Agc.GainDb;
    public bool HasFallenBack => _fellBack != 0;
    /// <summary>Added latency: RNNoise look-ahead plus <see cref="BufferFrames"/> frames of worker buffering, in ms (40).</summary>
    public static double AddedLatencyMs => StudioChain.LatencyMs + BufferFrames * Frame / 48.0;

    public StudioProcessor(StudioChain chain, PullDelegate pullJitterBuffer, double renderPeriodMs, Action? threadInit = null)
    {
        _chain = chain;
        _pull = pullJitterBuffer;
        SetRenderPeriodMs(renderPeriodMs);
        _thread = new Thread(() => { try { threadInit?.Invoke(); } catch (Exception) { } Loop(); })
        { Name = "cordmic-studio", IsBackground = true, Priority = ThreadPriority.AboveNormal };
        _thread.Start();
    }

    public void SetRenderPeriodMs(double ms)
    {
        int period = (int)Math.Ceiling(Math.Max(0, ms) * 48);
        _targetFill = Math.Min(RingCap - Frame, BufferFrames * Frame + Math.Max(period, 48) + 96);
    }

    /// <summary>Mean / max processing time per 10 ms frame since the last call, in ms (for the log).</summary>
    public (double MeanMs, double MaxMs) TakeCpu()
    {
        lock (_statLock)
        {
            var r = _procN > 0 ? (_procSum / _procN, _procMax) : (double.NaN, double.NaN);
            _procSum = 0; _procMax = 0; _procN = 0;
            return r;
        }
    }

    /// <summary>Render thread: fills <paramref name="dst"/> (mono s16le) from the ring.</summary>
    public void Pull(Span<byte> dst)
    {
        int frames = dst.Length / 2, got = 0;
        lock (_ringLock)
        {
            if (_disposed)
            {
                // 0.6.1: a pull that races Dispose gets silence instead of touching a disposed event.
                dst.Clear();
                return;
            }
            int take = Math.Min(frames, _rCount);
            var sc = _scratch.AsSpan(0, Math.Min(frames, RingCap));
            for (int i = 0; i < take; i++)
            {
                sc[i] = _ring[_rRead];
                if (++_rRead == RingCap) _rRead = 0;
            }
            _rCount -= take;
            got = take;
            _gc.Real(sc[..take]);
            if (got < frames) _gc.Conceal(sc[take..]);
            for (int i = 0; i < sc.Length; i++) { short v = sc[i]; dst[2 * i] = (byte)v; dst[2 * i + 1] = (byte)(v >> 8); }
            if (frames > sc.Length) dst[(2 * sc.Length)..].Clear();
        }
        if (got < frames && Interlocked.Read(ref _framesDone) > WarmupFrames)
        {
            Interlocked.Increment(ref _underflows);
            NoteMiss("render pull found the Studio buffer empty");
        }
        Wake();
    }

    /// <summary>Wakes the worker. Tolerates a Dispose that happens between the ring check and the signal.</summary>
    private void Wake()
    {
        try { _wake.Set(); }
        catch (ObjectDisposedException) { }
    }

    /// <summary>True when the worker thread exited and the native RNNoise state was freed by <see cref="Dispose"/>.</summary>
    public bool NativeReleased { get; private set; }

    private void NoteMiss(string why)
    {
        long now = Stopwatch.GetTimestamp();
        bool trip;
        lock (_statLock)
        {
            Misses++;
            _missAt[_missIdx] = now;
            _missIdx = (_missIdx + 1) % 3;
            long oldest = _missAt[_missIdx];
            trip = oldest != 0 && now - oldest <= Stopwatch.Frequency;
        }
        if (trip && Interlocked.Exchange(ref _fellBack, 1) == 0) FellBack?.Invoke(why);
    }

    private int Fill() { lock (_ringLock) return _rCount; }

    /// <summary>
    /// Switches to <paramref name="next"/> (another preset) without stopping: the worker runs both chains on the same
    /// input for <see cref="SwapWarmFrames"/> frames, crossfades over the last one and frees the old chain. The jitter
    /// buffer and the ring are untouched, so there is no gap. Returns false (and leaves <paramref name="next"/> to the
    /// caller) if a swap is already pending or the processor is disposed.
    /// </summary>
    public bool ReplaceChain(StudioChain next)
    {
        lock (_ringLock)
        {
            if (_disposed || _pending is not null) return false;
            Volatile.Write(ref _pending, next);
        }
        Wake();
        return true;
    }

    private void Loop()
    {
        var sw = new Stopwatch();
        while (!_stop)
        {
            _wake.WaitOne(5);
            while (!_stop && _fellBack == 0 && Fill() < _targetFill)
            {
                _pull(_pcm);
                sw.Restart();
                for (int i = 0; i < Frame; i++) _f[i] = (short)(_pcm[2 * i] | (_pcm[2 * i + 1] << 8)) / 32768f;
                var pend = Volatile.Read(ref _pending);
                if (pend is not null)
                {
                    Array.Copy(_f, _f2, Frame);
                    pend.Process(_f2);
                    _chain.Process(_f);
                    if (++_swapFrames >= SwapWarmFrames)
                    {
                        for (int i = 0; i < Frame; i++)
                        {
                            float w = (i + 1) / (float)Frame;
                            _f[i] = _f[i] * (1 - w) + _f2[i] * w;
                        }
                        var old = _chain;
                        _chain = pend;
                        lock (_ringLock) _pending = null;
                        _swapFrames = 0;
                        Swaps++;
                        old.Dispose();
                    }
                }
                else _chain.Process(_f);
                for (int i = 0; i < Frame; i++) _s[i] = (short)Math.Clamp((int)Math.Round(_f[i] * 32768.0), short.MinValue, short.MaxValue);
                double ms = sw.Elapsed.TotalMilliseconds;
                lock (_ringLock)
                {
                    int w = (_rRead + _rCount) % RingCap;
                    for (int i = 0; i < Frame && _rCount < RingCap; i++)
                    {
                        _ring[w] = _s[i];
                        if (++w == RingCap) w = 0;
                        _rCount++;
                    }
                }
                lock (_statLock) { _procSum += ms; _procN++; if (ms > _procMax) _procMax = ms; }
                long done = Interlocked.Increment(ref _framesDone);
                if (ms > Frame / 48.0 && done > WarmupFrames) NoteMiss($"Studio frame took {ms:F1} ms");
            }
        }
    }

    /// <summary>
    /// Stops the worker. The native chain is freed only when the worker has exited; if it is still inside
    /// <see cref="StudioChain.Process"/> after the timeout, the chain is deliberately leaked (no use-after-free) and
    /// <see cref="NativeReleased"/> stays false. The wake event is left to the finalizer so a late render pull cannot
    /// hit a disposed handle.
    /// </summary>
    public void Dispose() => Dispose(TimeSpan.FromSeconds(1));

    public void Dispose(TimeSpan join)
    {
        lock (_ringLock)
        {
            if (_disposed) return;
            _disposed = true;
        }
        _stop = true;
        Wake();
        if (_thread.Join(join))
        {
            _chain.Dispose();
            _pending?.Dispose();
            _pending = null;
            NativeReleased = true;
        }
    }
}
